// A persisted shuffle bag: all phrases appear once before the next cycle.
// A separate key keeps motivation history out of financial data and JSON backups.
export function createSloganRotator(storage, random = Math.random) {
  const key = 'coinquest.slogans.v1';
  let queue = Promise.resolve(), memory = null, loaded = false;
  async function next() {
    let record = memory;
    if (!loaded) { loaded = true; try { const raw = await storage.get(key); if (raw) record = JSON.parse(raw); } catch {} }
    const valid = record && record.count === SLOGANS.length && Array.isArray(record.remaining)
      && record.remaining.every(i => Number.isInteger(i) && i >= 0 && i < SLOGANS.length)
      && new Set(record.remaining).size === record.remaining.length
      && Number.isInteger(record.last) && record.last >= 0 && record.last < SLOGANS.length
      && !record.remaining.includes(record.last);
    if (!valid || record.remaining.length === 0) {
      const last = Number.isInteger(record?.last) ? record.last : -1;
      const remaining = SLOGANS.map((_, i) => i);
      for (let i = remaining.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [remaining[i], remaining[j]] = [remaining[j], remaining[i]];
      }
      if (remaining.at(-1) === last) [remaining[0], remaining[remaining.length - 1]] = [remaining.at(-1), remaining[0]];
      record = { count: SLOGANS.length, remaining, last };
    }
    const index = record.remaining.pop();
    record.last = index;
    memory = record;
    try { await storage.set(key, JSON.stringify(record)); } catch {}
    return SLOGANS[index];
  }
  return { next() { const result = queue.then(next); queue = result.catch(() => {}); return result; } };
}
